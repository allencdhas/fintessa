#!/usr/bin/env node
// Copies deployed contract addresses + ABIs from ../contracts into this app's
// generated config, so the frontend never hand-copies addresses after a redeploy.
//
// Run manually after `forge script script/DeployBentoBox.s.sol --broadcast`, or via
// `npm run sync-addresses`. Safe to run even if a given chain hasn't been deployed to
// yet — it just skips that chain's file.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const contractsDir = path.resolve(__dirname, "../../contracts");
const outDir = path.resolve(__dirname, "../src/config/generated");

mkdirSync(outDir, { recursive: true });

// Known chain IDs we care about for this demo: local anvil + Base Sepolia.
const CHAIN_IDS = [31337, 84532];

const deployments = {};
for (const chainId of CHAIN_IDS) {
  const file = path.join(contractsDir, "deployments", `${chainId}.json`);
  if (existsSync(file)) {
    deployments[chainId] = JSON.parse(readFileSync(file, "utf8"));
    console.log(`[sync-addresses] loaded deployment for chain ${chainId}`);
  } else {
    console.log(`[sync-addresses] no deployment file for chain ${chainId}, skipping`);
  }
}

writeFileSync(path.join(outDir, "deployments.json"), JSON.stringify(deployments, null, 2) + "\n");

function loadAbi(artifactRelPath) {
  const file = path.join(contractsDir, "out", artifactRelPath);
  const artifact = JSON.parse(readFileSync(file, "utf8"));
  return artifact.abi;
}

const abis = {
  BentoBoxRouter: loadAbi("BentoBoxRouter.sol/BentoBoxRouter.json"),
  MockMintableERC20: loadAbi("MockMintableERC20.sol/MockMintableERC20.json"),
  V4Quoter: loadAbi("V4Quoter.sol/V4Quoter.json"),
};

writeFileSync(
  path.join(outDir, "abis.ts"),
  `// AUTO-GENERATED by scripts/sync-addresses.mjs — do not edit by hand.\n` +
    `export const bentoBoxRouterAbi = ${JSON.stringify(abis.BentoBoxRouter, null, 2)} as const;\n\n` +
    `export const mockMintableErc20Abi = ${JSON.stringify(abis.MockMintableERC20, null, 2)} as const;\n\n` +
    `export const v4QuoterAbi = ${JSON.stringify(abis.V4Quoter, null, 2)} as const;\n`
);

console.log(`[sync-addresses] wrote ${outDir}/deployments.json and abis.ts`);
